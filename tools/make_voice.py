#!/usr/bin/env python3
"""Condition assets/voice/*.wav (Piper output) into the embedded voice data:

    assets/voice.bin     all samples back to back, 16 kHz mono 16-bit little-endian
    src/voice_index.rs   (offset, length) in frames for each sample

Conditioning is tools/voice_common.py (resample, trim, normalise, fade). Run after
changing a WAV:

    python3 tools/make_voice.py

stdlib only. The spoken numbers are the click-threshold levels one..twenty_five.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from voice_common import RATE, load_sample

WORDS = [
    "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten",
    "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen",
    "eighteen", "nineteen", "twenty", "twenty_one", "twenty_two", "twenty_three",
    "twenty_four", "twenty_five",
]
CUES = ["ready"]

SRC = os.path.join(HERE, "..", "assets", "voice")
OUT_BIN = os.path.join(HERE, "..", "assets", "voice.bin")
OUT_RS = os.path.join(HERE, "..", "src", "voice_index.rs")


def main():
    blob = bytearray()
    entries = {}  # name -> (offset_frames, frames)
    for name in WORDS + CUES:
        s = load_sample(os.path.join(SRC, f"{name}.wav"))
        entries[name] = (len(blob) // 2, len(s))
        blob += struct.pack("<%dh" % len(s), *s)
        print(f"  {name}: {len(s)} frames ({len(s) / RATE * 1000:.0f} ms)")

    with open(OUT_BIN, "wb") as f:
        f.write(blob)

    lines = [
        "// Generated by tools/make_voice.py - do not edit.",
        "// (offset, length) in frames into assets/voice.bin (16 kHz mono i16 LE).",
        "",
        f"pub const NUMBERS: [(usize, usize); {len(WORDS) + 1}] = [",
        "    (0, 0), // 0: no sample",
    ]
    for w in WORDS:
        lines.append(f"    {entries[w]},")
    lines += ["];", "", f"pub const READY: (usize, usize) = {entries['ready']};", ""]
    with open(OUT_RS, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT_BIN} ({len(blob) / 1024:.0f} KB) and {OUT_RS}")


if __name__ == "__main__":
    main()
