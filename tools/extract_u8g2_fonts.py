#!/usr/bin/env python3
"""Pull the few U8g2 fonts the UI uses out of U8g2's u8g2_fonts.c into
src/assets/ui_fonts.h, so the firmware doesn't carry (or compile) the 40 MB
font file or the rest of the U8g2 library. Arduino_GFX renders these arrays
itself (Arduino_GFX::setFont(const uint8_t*)).

    curl -O https://raw.githubusercontent.com/olikraus/u8g2/master/csrc/u8g2_fonts.c
    python3 tools/extract_u8g2_fonts.py u8g2_fonts.c

Fonts are BSD-licensed (see https://github.com/olikraus/u8g2/wiki/fntgrp);
change FONTS and re-run to add or drop one.
"""
import pathlib
import re
import sys

FONTS = [
    "logisoso18_tf", "logisoso22_tf", "logisoso24_tf", "logisoso26_tf",
    "logisoso28_tf", "logisoso34_tf", "logisoso38_tf",
    "helvR12_tf", "helvR14_tf", "helvR18_tf", "helvR24_tf",
]

src = pathlib.Path(sys.argv[1]).read_text(errors="replace")
out = ["// Generated by tools/extract_u8g2_fonts.py from U8g2's u8g2_fonts.c - do not edit.",
       "// U8g2 fonts: https://github.com/olikraus/u8g2 (BSD 2-clause for the fonts' glyph data",
       "// per each font's own Copyright line below).",
       "#pragma once",
       "#include <stdint.h>",
       "#define U8G2_FONT_SECTION(name)", ""]
for name in FONTS:
    full = "u8g2_font_" + name
    start = src.find("const uint8_t " + full + "[")
    if start < 0:
        sys.exit("font not found: " + full)
    end = src.index(";\n", start)
    decl = src[start:end + 1]
    # The comment block just above the declaration names the font and its licence.
    head = src[max(0, start - 400):start]
    comment = " ".join(l.strip() for l in head.splitlines() if "Fontname" in l or "Copyright" in l)
    # "const uint8_t name[N] U8G2_FONT_SECTION(...) =" -> unsized inline array (one copy across files)
    decl = re.sub(r"^const uint8_t (\w+)\[\d+\]", r"inline const uint8_t \1[]", decl)
    out.append("// " + comment)
    out.append(decl)
    out.append("")
pathlib.Path(__file__).resolve().parents[1].joinpath("src/assets/ui_fonts.h").write_text("\n".join(out))
print("wrote", len(FONTS), "fonts")
