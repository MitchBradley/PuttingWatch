"""PlatformIO pre-build script: write include/fw_version.h from `git describe`.

A header (not a -D flag) so a new commit only recompiles the file(s) that
include it - a build flag would change for every source, including large libraries and
Arduino_GFX, and defeat the fast routine rebuilds platformio.ini is tuned for.
The file is only rewritten when the version actually changes.

Release tags look like v1.2.0 and the leading "v" is dropped, so a release
build reports exactly "1.2.0" - the same string the OTA manifest carries.
Between tags git describe gives 1.2.0-3-gabc1234, and a "-dirty" suffix marks
uncommitted changes; the update logic treats anything that isn't a plain
release version as a development build.
"""
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env["PROJECT_DIR"]  # noqa: F821


def git(*args):
    try:
        return subprocess.check_output(
            ["git", *args], cwd=project_dir, stderr=subprocess.DEVNULL
        ).decode().strip()
    except Exception:
        return ""


version = git("describe", "--tags", "--always", "--dirty") or "unknown"
if len(version) > 1 and version[0] == "v" and version[1].isdigit():
    version = version[1:]
content = (
    "// Generated by tools/fw_version.py at build time - do not edit or commit.\n"
    "#pragma once\n"
    f'#define FW_VERSION "{version}"\n'
)

path = os.path.join(project_dir, "include", "fw_version.h")
try:
    with open(path) as f:
        unchanged = f.read() == content
except OSError:
    unchanged = False
if not unchanged:
    with open(path, "w") as f:
        f.write(content)
print(f"fw_version: {version}")
